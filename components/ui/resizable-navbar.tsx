"use client";

/**
 * Resizable Navbar — ported from Aceternity UI (MIT), theme-adapted.
 *
 * A nav that starts full-width at the top of the page and, once you
 * scroll, shrinks into a floating glass pill (40% width, dropped 20px,
 * blurred). Demo semantics are `sticky top-20`; pass a `fixed` className
 * and an external `scrolled` prop for a fixed page nav.
 *
 * JOLT adaptations (recorded):
 * - @tabler/icons-react icons replaced with inline SVGs (no new dep).
 * - `NavbarLogo` accepts children so the site's own mark renders.
 * - "gradient" button variant: blue → our accent orange.
 * - `scrolled` prop: external scroll control for fixed navs (the demo
 *   measures a sticky target, which doesn't work at `fixed top-0`).
 * - MobileNavToggle is a real <button> with aria-label + aria-expanded.
 */

